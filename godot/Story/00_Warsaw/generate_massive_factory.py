# Helper to create dialogue
def d(char, exp, text, side="left"):
    return {
        "character": char,
        "expression": exp,
        "text": text,
        "type": "dialogue",
        "side": side
    }
def d_enter(char, exp, text, side="left"):
    return {
        "character": char,
        "expression": exp,
        "text": text,
        "type": "dialogue",
        "side": side,
        "animation": "enter"
    }
def cmd(name, args):
    return {"name": name, "args": args, "type": "command"}

def t(text):
    return {"character": "", "text": text, "type": "dialogue"}

